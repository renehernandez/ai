import { join } from "node:path";
import {
  parseRoute,
  type RouteTable,
  readRoutes,
} from "../../hooks/pi/launch.ts";

export const HERDR_TEMPLATES_TARGET = "~/.config/herdr-core/templates";
const LAUNCHER = "~/.agents/hooks/pi/launch.ts";
// Roles a person starts by name; workers are launched only by the workflow runner.
const PERSON_ROLES = ["planner-astra", "planner-fable"];

export type HerdrTemplate = { file: string; content: string };

function quote(word: string): string {
  return /^[\w./:@~-]+$/.test(word)
    ? word
    : `'${word.replaceAll("'", "'\\''")}'`;
}

// herdr-core sends a nonempty body as the first prompt, so the body stays empty and the task alone starts the turn.
function render(
  name: string,
  description: string,
  argv: string[],
): HerdrTemplate {
  const command = argv.map(quote).join(" ");
  return {
    file: `${name}.md`,
    content: `---\nname: ${name}\ndescription: ${description} Generated by AX from hooks/pi/routes.json.\ncommand: ${command}\n---\n`,
  };
}

// One template per orchestrator route and per consult planner, generated from the tracked route table.
export function herdrTemplates(table: RouteTable): HerdrTemplate[] {
  const orchestrator = table.orchestrator;
  if (!orchestrator) throw new Error("herdr_templates_invalid: orchestrator");
  const templates = orchestrator.routes.map((spec, index) => {
    const route = parseRoute(spec);
    return render(
      index === 0 ? "ax-orchestrator" : `ax-orchestrator-${route.model}`,
      `${orchestrator.label} on ${spec}.`,
      [
        "node",
        LAUNCHER,
        "orchestrator",
        ...orchestrator.routes,
        "--provider",
        route.provider,
        "--model",
        route.model,
        "--thinking",
        route.thinking,
      ],
    );
  });
  for (const role of PERSON_ROLES) {
    const entry = table[role];
    if (!entry) throw new Error(`herdr_templates_invalid: ${role}`);
    const route = parseRoute(entry.routes[0]);
    templates.push(
      render(`ax-${role}`, `${entry.label} on ${entry.routes[0]}.`, [
        "node",
        LAUNCHER,
        role,
        route.provider,
        route.model,
        route.thinking,
      ]),
    );
  }
  return templates;
}

export function readHerdrTemplates(sourceRoot: string): HerdrTemplate[] {
  return herdrTemplates(readRoutes(join(sourceRoot, "hooks/pi/routes.json")));
}
